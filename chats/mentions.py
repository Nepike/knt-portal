"""Упоминания: кого позвали в сообщении.

Считаем ПО ТЕКСТУ, а не по тому, что прислала вкладка вместе с формой. Так упоминание
переживает правку сообщения, работает, когда имя набрали руками мимо подсказки, и его
нельзя подделать: позвать можно только того, кто в этом чате состоит.

Пишем «Фамилия Имя» — тем же порядком, каким имя выведено везде на сайте (User.full_name).
"""

from users.models import User

# Дешёвая отсечка: собачки нет — и спрашивать базу не о чем. Сообщений с упоминанием
# меньшинство, а список участников курсового чата — это сотни строк на каждую отправку.
MARK = "@"


def mentioned(chat, text):
    """Участники чата, чьё имя названо в тексте после собачки."""
    if MARK not in text:
        return []
    people = User.objects.filter(chat_memberships__chat=chat).only("name", "surname")
    return [person for person in people if f"{MARK}{person.full_name}" in text]


def remember(message):
    """Переписать упоминания сообщения по его тексту. Зовётся и при отправке, и при правке."""
    message.mentions.set(mentioned(message.chat, message.text))
