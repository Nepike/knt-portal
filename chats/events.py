"""Публикация событий чата в channel layer.

Разметку получатель забирает сам обычным HTTP-запросом: пузырь у каждого свой —
своё сообщение или чужое, есть ли право стереть, рисовать ли аватар. Поэтому
наружу летит не содержимое, а повод за ним прийти.

Но повод стоит денег. Раньше событие говорило только «в чате N что-то произошло»,
и каждая вкладка каждого участника шла на сервер хотя бы за счётчиком непрочитанных —
на курсе это под сотню запросов на одно сообщение, и почти все впустую. Поэтому
о НОВОМ сообщении событие говорит ещё две вещи: чьё оно и какое по счёту. Этого
хватает, чтобы поправить счётчик у себя и не дёргать ленту из-за собственного
сообщения, которое на экране уже есть.
"""

from asgiref.sync import async_to_sync
from channels.layers import get_channel_layer


def chat_group(chat_id):
    return f"chat.{chat_id}"


def user_group(user_id):
    return f"user.{user_id}"


def notify_chat(chat_id, message=None, kind=None):
    """`message` — если в чате появилось новое сообщение, иначе `kind` — что изменилось.

    Вид изменения нужен по той же причине, что и данные о новом сообщении: без него
    любая мелочь означала для КАЖДОЙ вкладки три запроса — за счётчиком, за списком
    чатов и за самой лентой. А меняют они разное: реакция не трогает ни счётчик, ни
    список (текст последнего сообщения тот же), правка меняет только строку списка,
    и лишь удаление — и то и другое. Разбирает это клиент (components.js).
    """
    event = {"type": "chat.event", "chat": chat_id}
    if message is not None:
        event["msg"] = message.pk
        event["author"] = message.author_id or 0  # 0 — служебная строка, автора у неё нет
    if kind:
        event["kind"] = kind
    _publish(chat_group(chat_id), event)


def notify_read(chat_id, user_id, upto_id):
    """Собеседник дочитал до сообщения `upto_id`. Только для ЛС.

    Там это одно событие на одного человека, и оно окупает живые галочки «прочитано».
    В группе тот же ответ означал бы рассылку курсора каждого каждому на каждый опрос —
    ровно ту лавину, ради ухода от которой событие и обросло данными (см. выше). Поэтому
    в группах прочтение спрашивают по нажатию.
    """
    _publish(chat_group(chat_id), {"type": "chat.event", "chat": chat_id, "read": upto_id, "by": user_id})


def notify_joined(user_id, chat_id):
    """Человека добавили в чат: в группе чата его сокета ещё нет, зовём по личной."""
    _publish(user_group(user_id), {"type": "chat.joined", "chat": chat_id})


def notify_left(user_id, chat_id):
    """Вышел или исключён: иначе сокет остался бы в группе и слушал чужую переписку."""
    _publish(user_group(user_id), {"type": "chat.left", "chat": chat_id})


def _publish(group, payload):
    layer = get_channel_layer()
    if layer is None:  # слой не настроен (например, отдельная management-команда)
        return
    async_to_sync(layer.group_send)(group, payload)
