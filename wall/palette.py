"""Палитра Стены.

Цвет хранится числом — индексом в этом списке, по байту на клетку. Отсюда главное
правило: с открытия доски список только дополняется. Переставить или выкинуть цвет
значит перекрасить все уже поставленные пиксели и все архивные доски заодно.

Сетка «12 тонов на 8 светлот» посчитана в OKLCH — там светлота мерится так, как её
видит глаз. Восемь ступеней, а не четыре: цвета в рисунке нужны не поодиночке, а
лесенкой — тень, основной, блик, — и на четырёх ступенях лесенки не выходит, соседние
цвета слишком далеко. Насыщенность внутри строки одна на все двенадцать: если брать
её долей от предельной, синий с фиолетовым в строке кричат, а жёлтый выглядит грязью.
По строкам она идёт горбом — у самых тёмных и самых светлых цвета в природе почти нет.

Сетка вдобавок наклонена по кругу, тёплая половина светлее холодной: без наклона
жёлтый в тёмном ряду становится болотом, потому что жёлтого такой светлоты не бывает.
Углы подобраны под названия, а не ровным шагом: «жёлтый» в OKLCH стоит на 105°, и
ровная сетка через 30° сдвигала бы половину названий мимо цвета.

Отдельным рядом идут нейтральные, от туши до мела: это контур, тень и блик, без них
рисунок не читается. Они тёплые, а фон доски холодный — спутать нельзя. Середины в
ряду нет намеренно: там стоит сам бетон, и получают его стиранием.

Считалось скриптом по (светлота, насыщенность, тон); значения проверены на попадание
в sRGB — там, где цвет упирался в край монитора, насыщенность подрезана.
"""

