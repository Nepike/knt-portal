"""Ограничитель частоты запросов.

Живёт в core, а не рядом с одним из пользователей: им пользуются и восстановление пароля,
и поддержка — обе формы открыты без логина, то есть доступны кому угодно из интернета.

Счёт идёт в кэше, а он на проде общий для всех воркеров (Redis, см. settings/prod.py) —
иначе у каждого процесса был бы свой счётчик и лимит на деле оказывался бы кратно выше.
"""

import ipaddress
import logging

from django.core.cache import cache

logger = logging.getLogger(__name__)


def throttled(key, limit, window=3600):
    """Фиксированное окно: True — лимит исчерпан."""
    try:
        return _count(key, window) > limit
    except Exception:  # noqa: BLE001 — какой именно, зависит от бекенда кэша
        # Кэш на проде — отдельный сервис, и он может лечь. Считать в такой момент,
        # что лимит исчерпан, значит закрыть вход всем, кто забыл пароль: ограничитель
        # не должен быть причиной, по которой страница не работает. Пропускаем и
        # жалуемся в лог — тем же порядком, что telegram.notify при мёртвой очереди.
        logger.exception("Кэш недоступен, ограничитель пропускает «%s»", key)
        return False


def _count(key, window):
    """Который это по счёту вызов в текущем окне.

    Окно заводит cache.add: он кладёт значение, только если ключа ещё нет, и именно он
    ставит время жизни. Дальше идёт incr — он счётчик увеличивает, а срок НЕ продлевает,
    поэтому окно остаётся фиксированным и не уползает от постоянного долбления.
    """
    if cache.add(key, 1, window):
        return 1
    try:
        return cache.incr(key)
    except ValueError:
        # Ключ истёк между add и incr — значит окно уже закончилось, начинаем новое.
        cache.set(key, 1, window)
        return 1


def client_ip(request):
    """Адрес клиента — тот, что видел наш nginx, а не тот, что клиент назвал сам.

    X-Real-IP nginx ставит сам и присланное значение затирает (nginx.conf). А в
    X-Forwarded-For он дописывает настоящий адрес в КОНЕЦ, и первым остаётся то, что
    прислал клиент: сменой этого заголовка обходились лимиты, а «unknown» в нём ронял
    вход — строка уезжала в поле адреса сессии. Без nginx (разработка) заголовка нет,
    берём адрес соединения. Не адрес — значит пусто.
    """
    for raw in (request.META.get("HTTP_X_REAL_IP"), request.META.get("REMOTE_ADDR")):
        try:
            return str(ipaddress.ip_address((raw or "").strip()))
        except ValueError:
            continue
    return ""
