"""Бета-режим: наружу открыта только часть сайта.

Сайт переехал на боевой домен раньше, чем проверены все разделы. Пока идёт проверка,
обычный пользователь ходит по материалам и библиотеке, остальное видит только персонал.
`OPEN` — список РАЗРЕШЁННОГО. Открыть раздел = ДОБАВИТЬ сюда имена его урлов; всё, чего
в списке нет, для не-персонала закрыто. Больше нигде ничего править не надо.

Разрешаем поимённо, а не запрещаем: забыть внести раздел в список — досадно и заметно
в тот же день, забыть внести в запреты — значит выставить наружу непроверенное и об этом
не узнать.

Имена урлов, а не пути: путь можно поменять, а имя живёт в шаблонах и в `reverse`,
и разойтись они не могут.
"""

from django.conf import settings

OPEN = {
    # Материалы и библиотека: смотреть и скачивать. Добавление и правка — ниже, их нет.
    "material_list",
    "material_detail",
    "book_list",
    "book_detail",
    "file_download",
    "media_image",
    # Обсуждение под материалом. Открыто: «только чтение» относится к загрузке файлов,
    # а комментарии — часть самой страницы материала, и без них раздел куцый.
    "comment_add",
    "comment_edit",
    "comment_delete",
    "comment_like",
    "comment_dislike",
    # Вход и восстановление пароля. Без них в бету не попасть даже персоналу.
    "login",
    "logout",
    "password_change",
    "password_reset",
    "password_reset_done",
    "password_reset_confirm",
    "password_reset_complete",
    # Аккаунты заводит человек с правом users.add_user (вьюха это и проверяет),
    # регистрации с улицы на сайте нет вовсе.
    "user_new",
    # Поддержка: если её закрыть, о поломке некому будет сообщить.
    "support",
    # Корень домена — редирект на материалы.
    "home",
}


def locked(request):
    """Закрыт ли текущий адрес для этого пользователя."""
    if not settings.BETA:
        return False
    if request.user.is_authenticated and request.user.is_staff:
        return False
    match = request.resolver_match
    return not match or match.url_name not in OPEN
