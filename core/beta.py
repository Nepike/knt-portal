"""Бета-режим: пара страниц, которых наружу пока показывать нечего.

Сайт переехал на боевой домен раньше, чем были проверены все разделы. Проверка прошла,
и на 14 авг 2026 закрыт ровно один адрес — профиль: страница есть, но она заглушка,
её ещё не делали. Всё остальное открыто всем вошедшим.

`CLOSED` — список ЗАПРЕЩЁННОГО, и это сознательный разворот. Начинали наоборот, со списка
разрешённого: пока закрыта была половина сайта, забыть внести раздел в белый список было
не страшно (заметно в тот же день), а забыть внести в чёрный — значило выставить наружу
непроверенное и не узнать. Теперь соотношение обратное: в белом списке пришлось бы держать
160 имён ради одного закрытого, и цена забытого имени сменилась на противоположную —
работающий раздел молча отвечал бы 403 на бою. Когда закрытых страниц снова станет много,
разворачивать обратно.

Имена урлов, а не пути: путь можно поменять, а имя живёт в шаблонах и в `reverse`,
и разойтись они не могут.
"""

from django.conf import settings

CLOSED = {
    # Профиль: аватар, ФИО и контакты — но ни уровня, ни значков, ни инвентаря.
    # Пока их нет, показывать нечего. Следствие: имя и аватар автора в отзывах,
    # комментариях и чатах ведут на плашку «закрыто» — так решено осознанно.
    "profile",
}


def locked(request):
    """Закрыт ли текущий адрес для этого пользователя."""
    if not settings.BETA:
        return False
    if request.user.is_authenticated and request.user.is_staff:
        return False
    match = request.resolver_match
    return bool(match) and match.url_name in CLOSED
