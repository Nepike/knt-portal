"""Спека: что считается готовым медиафайлом.

Договор целиком — в `docs/media-pipeline.md`. Коротко: **сайт не конвертирует.**
Файл печётся снаружи — руками по документированной команде или пекарней на машине
с видеокартой, — а здесь только проверяется и отвергается с внятной причиной.

Числа отдаются наружу ручкой `GET /intake/spec/`, и пекарня сверяет свой результат
теми же функциями, которыми его потом встретит сайт. То есть «прошло у меня»
и «приняли на сайте» — буквально одна проверка, а не две похожие.

Модуль **не импортирует Django** и не должен начать: его берёт с собой `tools/bake.py`
на машину, где ни проекта, ни настроек нет. На это есть тест — иначе случайный
`from django...` обнаружился бы уже на той машине.

Команду ffmpeg сайт наружу не отдаёт, хотя в наброске договора было так. Исполнять
командную строку, присланную по сети, — плохая форма даже когда сеть своя, а кодек
всё равно выбирается на месте (есть NVENC — им, нет — libx264). Один экземпляр нужен
ТРЕБОВАНИЯМ; способ их достичь — дело пекарни.

Готовое бывает двух видов, и мерки у них разные:

* `Clip` — один короткий файл целиком (косметика). Меряется точно: размер, длина, вес.
* `Ladder` — набор HLS (лекция). Одним числом не измеришь — там несколько дорожек,
  тысячи сегментов и манифесты, поэтому меряется описание набора, а не файл.
"""

from collections import namedtuple
from math import ceil

MB = 1024 * 1024

# Как зовутся заглавные файлы готового набора HLS. Имена общие для пекарни и сайта:
# пекарня их пишет, сайт по ним находит набор, зная один только префикс папки.
# Разъехаться им нельзя — лекция просто не откроется.
MASTER = "master.m3u8"
POSTER = "poster.jpg"

# width/height — точный размер готового файла, а не «примерно такие пропорции»:
# видео печётся с нуля по этой же строке, и промахнуться мимо неё можно только ошибкой.
# У картинок мерка мягче (`cosmetics/specs.py`) — полсотни рамок достались со старого
# сайта разнокалиберными, и переделать их уже некому. Расхождение намеренное: форма
# админки принимает и сделанное руками, а рецепт описывает работу машины.
#
# poster_bytes — потолок постера. Он тоже часть готового: постер виден, пока видео не
# подставлено, и качается на каждом показе витрины, а видео — только у попавших в экран.
Clip = namedtuple("Clip", "title width height seconds max_bytes audio poster_bytes")

# heights — ступени лесенки, сверху вниз. Это ПОТОЛОК, а не список обязательных дорожек:
# вверх не растягиваем никогда, поэтому из записи 720p выйдет одна дорожка, а из 4K —
# всё равно 1080p. Потолок веса у лекции не задан: двухчасовую запись одним числом
# не ограничить, а обрезать её по весу было бы враньём.
Ladder = namedtuple("Ladder", "title heights fps segment audio_kbps poster_bytes")

SHAPES = {Clip: "clip", Ladder: "ladder"}
KINDS = {name: kind for kind, name in SHAPES.items()}

RECIPES = {
    "cosmetic-header": Clip("шапка профиля", 1536, 256, 8, 2 * MB, audio=False, poster_bytes=MB // 2),
    "cosmetic-background": Clip("фон профиля", 1920, 1080, 8, 8 * MB, audio=False, poster_bytes=MB),
    # Две ступени, а не три: место дороже лишнего промежуточного качества. 30 кадров —
    # это ПОТОЛОК частоты: у доски с мелом от шестидесяти нет никакой пользы, а работы
    # и веса вдвое больше. Сегмент 6 с — обычная длина для записи, которую смотрят
    # подряд: короче значит больше запросов, длиннее — дольше переключение качества.
    "lecture": Ladder("лекция", heights=(1080, 720), fps=30, segment=6, audio_kbps=128, poster_bytes=MB),
}


def payload():
    """Спека как обычный словарь — для JSON и для пекарни.

    `shape` добавляем явно: по одним полям пекарня не догадается, чего от неё ждут,
    а угадывать по набору ключей — способ однажды угадать неверно.
    """
    return {name: {"shape": SHAPES[type(r)], **r._asdict()} for name, r in RECIPES.items()}


def recipe_from(data):
    """Рецепт из того, что прислал сайт.

    Незнакомое поле — не мелочь, а признак, что пекарня отстала от репозитория. Печь
    по половине требований хуже, чем не печь: файл выйдет правдоподобным и отвалится
    уже на приёмке, когда человек будет думать, что дело сделано.
    """
    data = dict(data)
    shape = data.pop("shape", None)
    kind = KINDS.get(shape)
    if kind is None:
        raise ValueError(f"пекарня не знает такого вида рецепта: {shape!r}. Обнови репозиторий")

    unknown = sorted(set(data) - set(kind._fields))
    if unknown:
        raise ValueError(f"сайт прислал поля, которых пекарня не знает: {', '.join(unknown)}. Обнови репозиторий")
    missing = sorted(set(kind._fields) - set(data))
    if missing:
        raise ValueError(f"сайт не прислал: {', '.join(missing)}")

    if kind is Ladder:
        data["heights"] = tuple(data["heights"])  # в JSON кортежей нет, а сравнивать надо
    return kind(**data)


def check(recipe, info, size):
    """Причина отказа по одиночному файлу или None. `info` — то, что вернул `mp4.probe`.

    Отказ обязан говорить, ЧТО перепечь: у того, кто пёк, файл лежит рядом и выглядит
    нормально, так что наугад он будет пробовать до вечера.
    """
    if size > recipe.max_bytes:
        return f"тяжелее {recipe.max_bytes // MB} МБ ({size / MB:.1f} МБ)"
    if not info["faststart"]:
        # Оглавление (moov) в конце файла играть не запрещает: браузер догадается
        # дозапросить хвост по Range, и наша раздача Range умеет. Но это лишний круг
        # до первого кадра, а nginx тянет ради четырёх килобайт индекса целый ломоть
        # в 1 МБ. Чинится ремуксом без перекодировки — поэтому отказываем.
        return "нет faststart: оглавление в конце файла. Перепеки с -movflags +faststart"
    if info["audio"] and not recipe.audio:
        # Пояснение годится, пока рецепты без звука — только косметика.
        return "звуковая дорожка лишняя — это фон под текстом, перепеки с -an"
    if (info["width"], info["height"]) != (recipe.width, recipe.height):
        return f"ждали {recipe.width}×{recipe.height}, приехало {info['width']}×{info['height']}"
    if info["seconds"] > recipe.seconds:
        return f"длиннее {recipe.seconds} с ({info['seconds']:.1f} с)"
    return None


def check_ladder(ladder, made):
    """Причина отказа по готовому набору HLS или None.

    `made` — описание того, что вышло: `{"duration": секунды, "poster_bytes": N,
    "renditions": [{"height": 1080, "width": 1920, "segments": N, "bytes": N}, …]}`.

    Проверяем ОПИСАНИЕ, а не файлы: их тут тысячи, и открыть каждый нельзя ни сайту,
    ни пекарне. Зато число сегментов обязано сходиться с длительностью — на этом
    ловится оборванная выпечка, самый вероятный способ получить полулекцию.
    """
    made_heights = [r["height"] for r in made["renditions"]]
    if not made_heights:
        return "ни одной дорожки"
    if len(set(made_heights)) != len(made_heights):
        return f"дорожки повторяются: {sorted(made_heights)}"
    if (tallest := max(made_heights)) > (top := max(ladder.heights)):
        return f"дорожка {tallest}p выше верхней ступени {top}p"
    if made["duration"] <= 0:
        return "нулевая длительность"

    # Последний сегмент почти всегда неполный, поэтому ждём округление вверх и даём
    # разбежку в один: ffmpeg режет по опорным кадрам и на границе может сдвинуться.
    expected = ceil(made["duration"] / ladder.segment)
    for rendition in made["renditions"]:
        if abs(rendition["segments"] - expected) > 1:
            return (f"у дорожки {rendition['height']}p {rendition['segments']} сегментов, "
                    f"а по длительности {made['duration']:.0f} с ждали около {expected}")
    if made["poster_bytes"] > ladder.poster_bytes:
        return f"обложка тяжелее {ladder.poster_bytes // MB} МБ ({made['poster_bytes'] / MB:.1f} МБ)"
    return None
